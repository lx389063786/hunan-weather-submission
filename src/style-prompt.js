export function buildUserPrompt(input, source, context, weatherText = '', retryNote = '') {
  const org = getOrgName();
  const hint = source === 'daily'
    ? `这是每日自动写稿任务。执笔单位是${org}。请结合当前季节（11 月，小雪节气前后）基层气象工作特点，按「市县动态」栏目范文的写法，围绕以下主题撰写一篇稿件。`
    : `请根据以下素材，以${org}的名义撰写一篇「市县动态」栏目稿件。`;

  const referenceBlock = formatLocalContext(context);
  const parts = [hint];
  if (referenceBlock) parts.push('', referenceBlock);
  if (weatherText) parts.push('', weatherText);
  if (retryNote) parts.push('', retryNote);
  parts.push(
    '', '【本次已确定的写作主题（必须严格围绕它写，不得另选下方背景里的其他事件）】', input,
    '', '【要求】',
    '0. 【素材】里的主题是本次唯一选题，必须围绕它展开；下方【背景参考】只用于了解工作动态和文风，不得改换主题，也不要写背景里出现的其他事件。',
    '1. 题材必须有明确由头，从八类高价值题材中选，不要写日常巡检、常规值班这类流水账。',
    '2. 标题为「地名：工作动作＋成效」的自然句式，不要凑四字对仗，不要出现 XX 县等占位符。',
    '3. 正文按事实进程展开，段落起句和结尾方式参照范例句式，不要照抄范文内容。',
    '4. 不编造人名、精确数字、单位名称；素材不足时用概括性官方表述补足。',
    '5. 不要在文末写署名，直接输出成品稿件。',
  );
  return parts.join('\n');
}

export function parseDraft(raw) {
  const text = (raw || '').trim();
  const lines = text.split('\n');
  let title = '';
  let body = text;

  const first = lines[0]?.trim() || '';
  if (/^标题[：:]/.test(first)) {
    title = first.replace(/^标题[：:]\s*/, '').trim();
    body = lines.slice(1).join('\n').trim();
  } else {
    const m = text.match(/^([^\n]{4,60})[\n\r]+/);
    if (m && /[：:]/.test(m[1]) && m[1].length < 45) {
      title = m[1].trim();
      body = text.slice(m[0].length).trim();
    }
  }
  if (!title) title = '未命名稿件';
  return { title, content: body };
}
